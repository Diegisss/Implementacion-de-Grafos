    private void dibujar(Graphics g){
        for (Arista ari : grafo.getAri()) {
                ari.pintar(g);
        }
        
        for (int i = 0; i < grafo.verticesT(); i++) {
            Vertice v = grafo.getVertice(i);
            v.pintar(g);
        }
    }
    
    private void Mouse(){
        PanelDibujoGrafo.addMouseListener(new MouseAdapter(){
            @Override
            public void mousePressed(MouseEvent e){
                if (!insertarAri){
                    for(int i = 0; i<grafo.verticesT(); i++){
                        Vertice v = grafo.getVertice(i);
                        Rectangle r = new Rectangle(v.getX() - Vertice.d/2, v.getY() - Vertice.d/2, 
                                Vertice.d, Vertice.d);
                        if(r.contains(e.getPoint())){
                            verticeMouse = v; break;
                        }
                    }
                    return;
                }
                if(e.getButton() == MouseEvent.BUTTON3){
                    Vertice v = null;
                    for (int i = 0; i < grafo.verticesT(); i++) {
                        Vertice ve = grafo.getVertice(i);
                        Rectangle r = new Rectangle(ve.getX() - Vertice.d/2, ve.getY() - Vertice.d/2,
                                Vertice.d, Vertice.d);
                        
                        if(r.contains(e.getPoint())){
                            v = ve; break;
                        }
                    }
                    if (v == null) return;
                    
                    if(ORI == null){
                        ORI = v;
                        return;
                    }
                    
                    if(DESTI == null){
                        if(v == ORI) return;
                        DESTI = v;
                    }
                    
                    grafo.AgregarArista(ORI.getNombre(), DESTI.getNombre());
                    
                    implementartextArea mode = new implementartextArea(grafo);
                    Matriz.setText(mode.obMatriz()); 
                    
                    ORI = null; DESTI = null; insertarAri = false;
                    PanelDibujoGrafo.repaint();
                }
            }
            
            @Override
            public void mouseReleased(MouseEvent e){
                verticeMouse = null;
            }
        });
        PanelDibujoGrafo.addMouseMotionListener(new MouseAdapter() {
            @Override
            public void mouseDragged(MouseEvent e){
                if(verticeMouse != null){
                    verticeMouse.setX(e.getX());
                    verticeMouse.setY(e.getY());
                    PanelDibujoGrafo.repaint();
                }
            }
        });
    }
    

