    private void InsertarVerticeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_InsertarVerticeActionPerformed
        String NomVertice = JOptionPane.showInputDialog("Ingrese el nombre del vertice");
        
        if(NomVertice != null && !NomVertice.trim().isEmpty()){
            try{
                if (grafo.buscar(NomVertice) != -1) throw new Exception("el vertice con el nombre " + NomVertice + " ya existe");
                grafo.AgregarVertice(NomVertice.trim());
                
                //dado a que no ingresamos vertices dando click en el panel, se aplica una forma de ingresarlos
                //y acomodarlos aleatoriamente
                Vertice nuevoVertice = grafo.getVertice(grafo.verticesT() - 1);
                int x = 50 + (int)(Math.random() * (PanelDibujoGrafo.getWidth() - 100));
                int y = 50 + (int)(Math.random() * (PanelDibujoGrafo.getHeight() - 100));
                nuevoVertice.setX(x);
                nuevoVertice.setY(y);
                
                PanelDibujoGrafo.repaint();
                JOptionPane.showMessageDialog(null, "Vertice " + NomVertice + " agregado correctamente");
                
            }catch(Exception e){
                JOptionPane.showMessageDialog(null, "Ha ocurrido un error: " + e.getMessage(),"Error",JOptionPane.ERROR_MESSAGE);
            }
        }else
            return;
    }//GEN-LAST:event_InsertarVerticeActionPerformed

    private void EliminarVerticeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EliminarVerticeActionPerformed
        String NomVertice = JOptionPane.showInputDialog("Ingrese el nombre del vertice para eliminarlo");
        
        if (NomVertice != null && !NomVertice.trim().isEmpty()){
            try{
                if(grafo.buscar(NomVertice) == -1) throw new Exception("el vertice con el nombre " + NomVertice + " no existe");
                grafo.eliminarVertice(NomVertice.trim());
                
                
                PanelDibujoGrafo.repaint();
                
                implementartextArea mode = new implementartextArea(grafo);
                Matriz.setText(mode.obMatriz()); 
                
                JOptionPane.showMessageDialog(null, "Vertice " + NomVertice + " eliminado correctamente");
            }catch (Exception e){
                JOptionPane.showMessageDialog(null, "Ha ocurrido un error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }else
            return;
    }//GEN-LAST:event_EliminarVerticeActionPerformed

