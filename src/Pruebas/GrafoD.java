    private void EliminarAristaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EliminarAristaActionPerformed
        int O, D;
        String ori = JOptionPane.showInputDialog("¿Cual es el vertice origen?");
        String des = JOptionPane.showInputDialog("¿cual es el vertice destino?");
        
        if (ori != null && des != null && !ori.trim().isEmpty() && !des.trim().isEmpty()){
            try{
                if (grafo.buscar(ori) == -1) throw new Exception("Vertice origen " + ori + " no existe");
                if (grafo.buscar(des) == -1) throw new Exception("Vertice destino " + des + " no existe");
                
                O = grafo.buscar(ori);
                D = grafo.buscar(des);
                
                if(!grafo.aristaE(O, D)) throw new Exception("No existe arista " + ori + "," + des);
                
                grafo.EliminarArista(ori.trim(), des.trim());
                PanelDibujoGrafo.repaint();
                JOptionPane.showMessageDialog(null, "Arista " + ori + "," + des + " eliminada");
            }catch (Exception e){
                JOptionPane.showMessageDialog(null, "Ha ocurrido un error: " + e.getMessage(), "Error", 
                        JOptionPane.ERROR_MESSAGE);
            }
            
        }else
            return;
    }//GEN-LAST:event_EliminarAristaActionPerformed

    private void MostrarRecorridoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_MostrarRecorridoActionPerformed
        String op = (String)JOptionPane.showInputDialog(null, "¿QUE RECORRIDO HARA?", "RECORRIDOS", JOptionPane.INFORMATION_MESSAGE, null,
                new Object[]{"ANCHURA", "PROFUNDIDAD", "AMBOS"}, null);
        if(op == null) return;
        try{
            String vertice = JOptionPane.showInputDialog("Ingrese el vertice de origen");
            if (vertice == null) return;
            
            vertice = vertice.trim();

            implementartextArea mode = new implementartextArea(grafo); //Tengo otra clase que involucra a este objeto
            switch (op) {
                case "ANCHURA":
                    JtextRecorridos.setText(mode.obAnchura(vertice));
                    break;
                case "PROFUNDIDAD":
                    JtextRecorridos.setText(mode.obProfundidad(vertice));
                    break;
                case "AMBOS":
                    JtextRecorridos.setText(mode.obAnchura(vertice) + "\n" + mode.obProfundidad(vertice));
                    break;
                default:
                    JOptionPane.showMessageDialog(null, "ERROR");
            }
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, "Ha ocurrido un error: " + e.getMessage(), "Error",
                    JOptionPane.ERROR_MESSAGE);
        }
            
    }//GEN-LAST:event_MostrarRecorridoActionPerformed

